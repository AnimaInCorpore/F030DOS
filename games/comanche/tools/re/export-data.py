#!/usr/bin/env python3
"""Emit annotated DOS tables as 68k source, in the Falcon's byte order.

The conversion is not a byte swap. A swap would have to know where every
multi-byte field starts, and get it right silently. Instead each element is
DECODED from the image as a little-endian value and re-emitted as a dc.b, dc.w
or dc.l constant - the assembler then writes it big-endian, because that is
what a 68k assembler does. The element width comes from the `elem=` tag in the
annotation store, so a region that has not been measured is refused rather than
guessed at.

    python3 tools/re/export-data.py                     # everything tagged
    python3 tools/re/export-data.py sin_table_q31 ...   # named rows only

Writes build/re/dos-data.s and reports what it could not convert.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
IMAGE = ROOT / "re" / "unpacked" / "comanche-flat32.bin"
ANNOTATIONS = ROOT / "re" / "annotations.txt"
OUT = ROOT / "build" / "re" / "dos-data.s"

ROW = re.compile(r"^(\??)(table|data|string)\s+([0-9A-Fa-f]{8})\s+(\S+)\s+(\S+)\s*#(.*)$")
ELEM = re.compile(r"\belem=(\d+)\b")
DIRECTIVE = {1: "dc.b", 2: "dc.w", 4: "dc.l"}
PER_LINE = {1: 16, 2: 8, 4: 4}


def rows():
    for line in ANNOTATIONS.read_text(encoding="utf-8").splitlines():
        m = ROW.match(line)
        if not m or m.group(4) == "-":
            continue
        elem = ELEM.search(m.group(6))
        yield {
            "candidate": bool(m.group(1)),
            "kind": m.group(2),
            "addr": int(m.group(3), 16),
            "extent": int(m.group(4), 16),
            "name": m.group(5),
            "elem": int(elem.group(1)) if elem else (1 if m.group(2) == "string" else None),
        }


def main() -> int:
    wanted = set(sys.argv[1:])
    image = IMAGE.read_bytes()
    out = ["; Generated by tools/re/export-data.py - do not edit.",
           ";",
           "; DOS tables decoded from the little-endian image and re-emitted as 68k",
           "; constants, so the assembler writes them in the Falcon's byte order.",
           "; Each block carries the flat address it came from.",
           ""]
    done, skipped = [], []
    for r in rows():
        if wanted and r["name"] not in wanted:
            continue
        if r["elem"] is None:
            skipped.append((r["name"], "no elem= tag: element width not established"))
            continue
        if r["extent"] % r["elem"]:
            skipped.append((r["name"], f"extent {r['extent']:#x} is not a multiple of {r['elem']}"))
            continue
        if r["addr"] + r["extent"] > len(image):
            skipped.append((r["name"], "runs past the image"))
            continue
        block = image[r["addr"]:r["addr"] + r["extent"]]
        # A region that is entirely zero in the image holds nothing yet - it is
        # a buffer the program fills at run time, and the linker's zero fill is
        # all that is on disk. Byte order does not apply to it, and emitting it
        # would put kilobytes of dc.b 0 in front of the data that matters.
        if not any(block):
            skipped.append((r["name"],
                            f"zero-filled: {r['extent']:#x} bytes of "
                            f"uninitialised buffer, nothing to convert"))
            continue
        width, per = r["elem"], PER_LINE[r["elem"]]
        values = [int.from_bytes(block[i:i + width], "little")
                  for i in range(0, len(block), width)]
        out.append(f"; {r['name']} - DOS {r['addr']:08X}, {r['extent']:#x} bytes, "
                   f"{len(values)} x {width}-byte"
                   + (" (candidate)" if r["candidate"] else ""))
        out.append(f"{r['name']}")
        digits = width * 2
        for i in range(0, len(values), per):
            chunk = ",".join(f"${v:0{digits}X}" for v in values[i:i + per])
            out.append(f"        {DIRECTIVE[width]}    {chunk}")
        out.append("")
        done.append(r)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    total = sum(r["extent"] for r in done)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(done)} regions, {total} bytes")
    if skipped:
        print(f"{len(skipped)} regions not converted:")
        for name, why in skipped[:12]:
            print(f"  {name:28} {why}")
        if len(skipped) > 12:
            print(f"  ...and {len(skipped) - 12} more")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
