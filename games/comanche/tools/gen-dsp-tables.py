#!/usr/bin/env python3
"""Generate the DSP kernel's constant tables into src/dsp/tables.inc.

Two tables, both fixed by the depth schedule in proto.inc rather than by
anything the host sends, so they are built here instead of on the DSP.

RECIP_BASE is the reciprocal of each depth step, as a 1.23 fraction holding
1/(2*z). The halving is not cosmetic: the 56001's DIV produces a fractional
quotient, so 2**23/z cannot be computed on-chip at z=1 where it is exactly
1.0. Carrying 2**22/z instead keeps every entry inside the fraction, and the
kernel recovers the factor with one ASL after scaling by the projection.

ROW_OFFSET is row * bytes-per-row for the 16-bit destination surface. The
alternative is a multiply per emitted span, and on this part a multiply by 640
is a REP/ASL pair costing about twenty cycles in what is otherwise the cold
path of the inner loop.

Regenerated by tools/build-dsp.sh, so the tables cannot drift from the
schedule they are derived from.
"""

import itertools
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DTL = ROOT / "assets/extracted/comanche_hdd/HIGH.DTL"
PROTO = ROOT / "src/dsp/proto.inc"
SHARED = ROOT / "src/inc/comanche.s"
OUT = ROOT / "src/dsp/tables.inc"
PARITY_OUT = ROOT / "build/dsp_parity.s"


def const(name: str) -> int:
    text = PROTO.read_text()
    m = re.search(rf"^{name}\s+EQU\s+(\S+)", text, re.M)
    if not m:
        raise SystemExit(f"{name} not found in {PROTO}")
    expr = m.group(1)
    # proto.inc keeps to the two assemblers' shared subset: integers and
    # + - * / ( ). Both assemblers truncate integer division.
    expr = expr.replace("$", "0x").replace("/", "//")
    if not re.fullmatch(r"[0-9a-fx+\-*/() ]+", expr):
        raise SystemExit(f"{name} is not a simple expression: {expr}")
    return int(eval(expr))


def shared_const(name: str) -> int:
    text = SHARED.read_text()
    m = re.search(rf"^{name}\s*=\s*(\S+)", text, re.M)
    if not m:
        raise SystemExit(f"{name} not found in {SHARED}")
    return int(m.group(1), 0)


def bias_curve(depths, rows, horizon):
    """Row a level sample lands on, per depth step, from HIGH.DTL table 3.

    The original's projection adds a per-depth bias, not a constant horizon -
    page row 137 far off and 60 at the nearest step - so a single
    CMD_W_HORIZON word cannot express it, and the curve is carried the same
    way the reciprocal is.

    The conversion is 1:1: the DOS screen is 328x240, its terrain viewport is
    the scanline table's 199 usable rows, and page row k lands on screen row
    198 - k unscaled. floor(bias/256) rather than round, because the DOS page
    build takes the high byte of the clamped sum, so the level-sample row is
    exactly 198 - (bias >> 8) - which puts the nearest ring's bias, 60, on
    row 138, the measured windshield bottom of CONSOL1S.DTA. An earlier
    version read the view as 200 rows scaled by 240/200, which drew every
    slope 20% too steep and the far horizon 15 rows too low.

    The original HIGH.DTL is required. A flat horizon would be a different
    renderer, so missing source data is a build error.
    """
    if not DTL.is_file():
        raise SystemExit(f"missing original depth table: {DTL}")
    raw = DTL.read_bytes()
    count = struct.unpack_from("<I", raw, 0)[0]
    table = [list(struct.unpack_from("<250i", raw, 4 + 1000 * k)) for k in range(5)]
    z = list(itertools.accumulate(table[1]))[:count]
    bias = table[3][:count]
    out = []
    for d in depths:
        target = d * (1 << 22)              # the .DTL depths are 10.22
        pick = bias[-1]
        for zi, bi in zip(z, bias):
            if zi >= target:
                pick = bi
                break
        out.append(198 - (pick >> 8))       # 1:1: screen row = 198 - page row
    return out


def main() -> int:
    near = const("MARCH_NEAR_STEPS")
    far = const("MARCH_FAR_STEPS")
    far2 = const("MARCH_FAR2_STEPS")
    shift = const("TILE_FAR_SHIFT")
    shift2 = const("TILE_FAR2_SHIFT")
    rows = const("SCREEN_ROWS")
    cols = const("TERRAIN_COLS")

    depths = [i + 1 for i in range(near)]
    depths += [near + (i + 1) * (1 << shift) for i in range(far)]
    far_end = near + (far << shift)
    depths += [far_end + (i + 1) * (1 << shift2) for i in range(far2)]

    lines = [
        "; Generated by tools/gen-dsp-tables.py - do not edit.",
        ";",
        "; RECIP_BASE[i] = 2**22 / z_i as a 1.23 fraction, one entry per depth",
        "; step. The kernel scales it by the frame's projection and doubles the",
        "; result, which is where the 2**22 becomes 2**23.",
        ";",
        f"; Depth schedule: {near} unit steps, {far} steps of "
        f"{1 << shift} units, then {far2} steps of {1 << shift2} units, "
        f"reaching z={depths[-1]}.",
        "",
        f"RECIP_STEPS     EQU     {len(depths)}",
        "",
        "; Each table places itself. The kernel used to org once and rely on",
        "; the tables following in the order the Y map expects, which is a",
        "; coupling the assembler cannot check - it will not compare address",
        "; symbols in an IF.",
        "        org     y:Y_RECIP",
        "recip_base:",
    ]
    for pos in range(0, len(depths), 4):
        chunk = depths[pos:pos + 4]
        vals = ",".join(f"${(1 << 22) // z:06X}" for z in chunk)
        lines.append(f"        dc      {vals}")

    # The row offset is the SURFACE stride, not the ray count: the two only
    # coincide at 320 rays, and deriving it from TERRAIN_COLS silently broke
    # the 160-ray geometry's every offset.
    stride = shared_const("SCREEN_WIDTH") * 2
    lines += [
        "",
        "; ROW_OFFSET[row] = row * surface stride, the byte offset of a row in",
        "; the 16-bit destination surface. The stride is the screen's, which",
        "; is not the ray count's when the rays are two pixels wide.",
        "",
        f"ROW_OFFSET_LEN  EQU     {rows}",
        "",
        "        org     y:Y_ROWOFF",
        "row_offset:",
    ]
    for pos in range(0, rows, 4):
        vals = ",".join(f"${r * stride:06X}" for r in range(pos, min(pos + 4, rows)))
        lines.append(f"        dc      {vals}")

    horizon = shared_const("SCREEN_HORIZON")
    bias = bias_curve(depths, rows, horizon)
    lines += [
        "",
        "; BIAS[i] = the row a sample at the camera's level plane lands on, per",
        "; depth step, from HIGH.DTL table 3 at the original's own 1:1 rows:",
        "; screen row = 198 - (bias >> 8). See bias_curve in",
        "; tools/gen-dsp-tables.py.",
        "",
        "        org     y:Y_BIAS",
        "bias_table:",
    ]
    for pos in range(0, len(bias), 4):
        vals = ",".join(f"${v & 0xFFFFFF:06X}" for v in bias[pos:pos + 4])
        lines.append(f"        dc      {vals}")

    OUT.write_text("\n".join(lines) + "\n")

    # The 68030 parity marcher's projection table. Each entry mirrors the
    # kernel's own per-frame scaling bit for bit: the kernel multiplies the
    # loaded recip_base entry by (PROJ_SCALE << FIX_PROJ) and doubles twice
    # (the mpy's implicit doubling plus one ASL), then keeps accumulator bits
    # 24-47. So rscale = (floor(2**22/z) * (PROJ << 15) * 4) >> 24, and the
    # marcher's (dz * rscale) >> 15 lands on the same row the kernel's mpy
    # does, with no tolerance needed.
    proj = shared_const("PROJ_SCALE")
    plines = [
        "; Generated by tools/gen-dsp-tables.py - do not edit.",
        ";",
        "; Interleaved (rscale, bias) longword pairs, one per DSP depth step,",
        "; for the PARITY_TILE marcher in render.s. rscale mirrors the",
        "; kernel's frame_setup scaling exactly - see gen-dsp-tables.py -",
        "; and bias is bias_table verbatim, so (dz*rscale)>>15 + bias is the",
        "; kernel's projection to the bit.",
        "",
        f"; PROJ_SCALE {proj}, depth schedule as tables.inc.",
        "",
        "par_projection:",
    ]
    for z, b in zip(depths, bias):
        # Saturate exactly as the kernel does: frame_setup stores the scaled
        # accumulator through the 56001's limiter, so a product past the 1.23
        # positive range lands on $7FFFFF on both sides instead of wrapping
        # negative on one. At PROJ_SCALE 150 no entry reaches the limit -
        # saturation starts at a scale of 256 - so this is armour for a
        # future scale, not a live path.
        r = min((((1 << 22) // z) * (proj << 15) * 4) >> 24, 0x7FFFFF)
        plines.append(f"        dc.l    {r},{b}")
    PARITY_OUT.parent.mkdir(parents=True, exist_ok=True)
    PARITY_OUT.write_text("\n".join(plines) + "\n")

    print(f"wrote {OUT.relative_to(ROOT)}: {len(depths)} depths, {rows} rows, "
          f"bias {bias[0]}..{bias[-1]}")
    print(f"wrote {PARITY_OUT.relative_to(ROOT)}: parity projection at "
          f"PROJ_SCALE {proj}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
