#!/usr/bin/env python3
"""Generate (or check) docs/SUBSTITUTIONS.md from the source headers.

METHOD.md §4.2 requires the substitution surface to be enumerated in one place
and reviewed as a whole; the failure mode it guards against is the category
widening a defensible step at a time until it holds game logic. A list nobody
regenerates drifts, so this derives it from the tree.

    python tools/substitutions.py            # rewrite docs/SUBSTITUTIONS.md
    python tools/substitutions.py --check    # exit 1 if the file is stale

`Kind:` is the closed strategy set:

  translated  the Falcon code implements the DOS routine
  adapted     grounded in a DOS routine, reproduced by a different mechanism
              (surface port, DSP acceleration) -- METHOD.md §4.1 adaptation
  replaced    no DOS algorithm carried over -- the substitution set
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(HERE, 'docs', 'SUBSTITUTIONS.md')
KINDS = ('translated', 'adapted', 'replaced')


def headers():
    for path in sorted(glob.glob(os.path.join(HERE, 'src', '*.s'))):
        lines = open(path, encoding='utf-8').read().splitlines()
        for i, line in enumerate(lines):
            m = re.match(r'^;\s*Kind:\s*(\w+)\s*(?:-\s*(.+?))?\.?\s*$', line)
            if not m:
                continue
            fields = {'kind': m.group(1), 'note': m.group(2) or ''}
            for j in range(i - 1, max(-1, i - 8), -1):
                if not lines[j].lstrip().startswith(';'):
                    break
                d = re.match(r'^;\s*(DOS|Port):\s*(.+?)\.?\s*$', lines[j])
                if d:
                    fields.setdefault(d.group(1).lower(), d.group(2))
            for j in range(i + 1, min(len(lines), i + 4)):
                s = re.match(r'^;\s*Status:\s*(.+?)\s*$', lines[j])
                if s:
                    fields['status'] = s.group(1)
                if re.match(r'^[a-z_][a-z0-9_]*\s*$', lines[j]):
                    fields['label'] = lines[j].strip()
                    break
            fields['file'] = os.path.relpath(path, HERE).replace(os.sep, '/')
            fields['line'] = i + 1
            yield fields


def render():
    hs = list(headers())
    bad = [h for h in hs if h['kind'] not in KINDS]
    counts = {k: sum(1 for h in hs if h['kind'] == k) for k in KINDS}
    out = []
    out.append('# Substitutions\n')
    out.append('Generated by `tools/substitutions.py` from the `Kind:` field of '
               'every routine header. Do not edit by hand; re-run the tool.\n')
    out.append('METHOD.md §4.2 asks for the substitution surface to be closed '
               'and reviewable in one sitting. `replaced` is that surface: '
               'routines with no DOS algorithm behind them. `adapted` is not a '
               'substitution -- those are grounded in a DOS routine and differ '
               'only in mechanism (§4.1) -- but they are listed because the '
               'boundary between the two is where the category drifts.\n')
    out.append('| kind | routines |\n|---|---|')
    for k in KINDS:
        out.append('| `%s` | %d |' % (k, counts[k]))
    out.append('')
    if bad:
        out.append('**%d headers carry a Kind outside the closed set** and must '
                   'be corrected:\n' % len(bad))
        for h in bad:
            out.append('- `%s:%d` — `%s`' % (h['file'], h['line'], h['kind']))
        out.append('')
    for k in ('replaced', 'adapted'):
        out.append('## %s (%d)\n' % (k, counts[k]))
        out.append('| routine | file | DOS authority | note | status |')
        out.append('|---|---|---|---|---|')
        for h in hs:
            if h['kind'] != k:
                continue
            out.append('| `%s` | `%s:%d` | %s | %s | %s |' % (
                h.get('label', '?'), h['file'], h['line'],
                h.get('dos', '—'), h['note'] or '—', h.get('status', '—')))
        out.append('')
    return '\n'.join(out) + '\n', bad


def main():
    text, bad = render()
    if '--check' in sys.argv[1:]:
        have = open(DOC, encoding='utf-8').read() if os.path.exists(DOC) else ''
        if have != text:
            print('docs/SUBSTITUTIONS.md is stale — re-run tools/substitutions.py')
            return 1
        if bad:
            print('%d headers carry a Kind outside the closed set' % len(bad))
            return 1
        print('substitution registry matches the source')
        return 0
    os.makedirs(os.path.dirname(DOC), exist_ok=True)
    open(DOC, 'w', encoding='utf-8', newline='\n').write(text)
    print('wrote %s' % os.path.relpath(DOC, HERE))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
