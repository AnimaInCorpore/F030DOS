#!/usr/bin/env python3
"""Emit build/marcher_oracle.s: the camera of one captured DOS frame, as a
routine that pins the port's flight state to it.

Why this exists
---------------
src/render.s's status note has said for a while that the marcher's ARITHMETIC
is certified and its own output is not. Two layers were already measured
against the original's captured silhouettes and both score 100%:

  * tools/compare-marcher.py  - a Python model of 0000D950
  * tools/compare-port-tables.py - the port's OWN .DTL-derived tables and its
    decoded height map, fed through that model

Neither executes a line of 68030. This closes that gap by running the actual
instruction stream at the captured camera and diffing ring_silhouette against
the original's archive at [0x19E60].

The capture must be a COCKPIT frame - view variant [0x19D86] == 1. Early
attract records run variant 6, an external camera whose look direction is
animated apart from the helicopter heading, so [0x19D00] != [0x19D04] and no
value of flt_angle reproduces the basis the marcher used.
"""
import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("dump", help="a marcher-*.json from work/dump_marcher_tables.py")
    ap.add_argument("--out", default=str(ROOT / "build" / "marcher_oracle.s"))
    args = ap.parse_args()

    dump = json.loads(pathlib.Path(args.dump).read_text())
    st = dump["state"]

    variant = dump.get("view_variant_0x19D86")
    angle = dump.get("view_angle_0x19D00")
    if variant != 1 or angle is None:
        return err(f"{args.dump}: needs a cockpit capture (variant 1) carrying "
                   "[0x19D00]; capture one with the variant gate")
    if angle != st["view_angle_0x19D04"]:
        return err(f"{args.dump}: [0x19D00] != [0x19D04] - the view angle is "
                   "not the heading in this frame, so flt_angle cannot "
                   "reproduce the marcher's basis")

    name = pathlib.Path(args.dump).name
    if "shake_phase_0x19DBC" not in st:
        print("  note: capture predates the shake scalars; assuming phase 0",
              file=sys.stderr)
    lines = [
        "; Generated by tools/gen-marcher-oracle.py - do not edit.",
        f"; Source capture: {name}, replay cursor {dump.get('cursor')}, "
        f"view variant {variant}.",
        ";",
        "; The camera of one frame of the original, in the original's own",
        "; units: 10.22 position, the full 32-bit view angle, and the altitude",
        "; byte. Pinning these makes the marcher's output a function of the",
        "; port's tables and instruction stream alone.",
        "",
        "        global  marcher_oracle_seed",
        "        text",
        "        even",
        "marcher_oracle_seed",
        "        ; Force the runtime .DTL load once, so what gets certified is",
        "        ; src/dtl.s's loader and page builder rather than the tables",
        "        ; tools/prepare-original-test.py generated into the binary.",
        "        ; The settings block selects medium, which is the schedule the",
        "        ; capture was taken under, so a faithful loader reproduces the",
        "        ; generated tables exactly and the score is unchanged.",
        "        tst.w   marcher_oracle_loaded",
        "        bne     .loaded",
        "        move.w  #1,marcher_oracle_loaded",
        "        bsr     dtl_reload",
        ".loaded",
        f"        move.l  #${st['camera_x_0x19CD4']:08x},flt_x        ; [0x19CD4]",
        f"        move.l  #${st['camera_y_0x19CD8']:08x},flt_y        ; [0x19CD8]",
        f"        move.l  #${angle:08x},flt_angle    ; [0x19D00]",
        f"        move.l  #${st['roll_0x19CF8']:08x},flt_roll     ; [0x19CF8]",
        f"        move.l  #${st['pitch_0x19CFC']:08x},flt_pitch    ; [0x19CFC]",
        f"        move.b  #{st['altitude_0x19DFC']},player_altitude          ; [0x19DFC]",
        # 00007DB5's term. Usually zero - a flight only shakes just after it
        # hits something - but a capture taken mid-bounce would otherwise put
        # a constant offset through the whole backdrop comparison.
        f"        move.l  #{st.get('shake_phase_0x19DBC', 0)},flt_shake_phase   ; [0x19DBC]",
        "        move.l  #0,flt_shake_timer",
        # After dtl_reload, which sets this from [0x25DD9] - the capture may
        # have been taken with the marcher poked rather than the byte set.
        f"        move.w  #{1 if dump.get('lowres') else 0},terrain_lowres",
        # The view variant, and it has to be pinned like everything else now
        # that 00007D25 is ported. The renderer takes [0x19CB0]/[0x19CB4] and
        # the backdrop takes [0x19CF8]/[0x19CFC], which view_basis_build
        # derives through the variant's own handler - so an attract frame that
        # had already switched to the chase camera would march from fifteen
        # cells behind the pinned camera and score as a renderer fault. The
        # captures this oracle accepts are cockpit frames by construction:
        # src/render.s's certification note says so, and variants 6 and 7
        # animate the look direction apart from the flight angle, which is
        # exactly why they cannot be reproduced from a pinned flt_angle alone.
        "        move.b  #1,view_variant         ; [0x19D86], a cockpit frame",
        "        rts",
        "",
        "        even",
        "marcher_oracle_loaded",
        "        dc.w    0",
        "",
    ]
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"wrote {out} from {name}")
    print(f"  camera 0x{st['camera_x_0x19CD4']:08X},0x{st['camera_y_0x19CD8']:08X} "
          f"angle 0x{angle:08X} alt {st['altitude_0x19DFC']} "
          f"rings {st['ring_count_0x19EE0']} "
          f"marcher {'96-column' if dump.get('lowres') else '192-column'}")
    return 0


def err(message: str) -> int:
    print(message, file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
