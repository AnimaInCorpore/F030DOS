from trace_replay_flight import REPLAY_ARMED, read_block, write_block

REG_NUMBERS = {"eax": 0, "ecx": 1, "edx": 2, "ebx": 3, "esp": 4, "ebp": 5,
               "esi": 6, "edi": 7, "eip": 8, "eflags": 9}
FLAT_IMAGE = os.path.join(ROOT, "re", "unpacked", "comanche-flat32.bin")


class Original:
    """The running original, held at the start of a replay."""

    def __init__(self, hdd, wait=240.0, port=4697, gport=4698):
        self.args = (hdd, wait, port, gport)
        with open(hdd + ".geom.json", encoding="utf-8") as f:
            g = json.load(f)
        port = int(os.environ.get("QMP_PORT", port))
        gport = int(os.environ.get("GDB_PORT", gport))
        cmd = [QEMU, "-M", "pc", "-cpu", "486", "-m", "16",
               "-drive", f"file={hdd},format=raw,if=none,id=hd0,snapshot=on",
               "-device", f"ide-hd,drive=hd0,bus=ide.0,unit=0,cyls={g['cyls']},"
                          f"heads={g['heads']},secs={g['secs']}",
               "-boot", "c", "-display", "none", "-vga", "std", "-no-reboot",
               "-qmp", f"tcp:127.0.0.1:{port},server=on,wait=off",
               "-gdb", f"tcp:127.0.0.1:{gport}"]
        self.proc = subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.STDOUT)
        self.qmp = Qmp(port)
        if not wait_for_program(self.qmp, self.proc, wait):
            raise RuntimeError("the program never became resident")
        self.gdb = Rsp(gport, timeout=wait)
        armed = linear(REPLAY_ARMED)
        self.gdb.set_break(armed)
        if self.gdb.cont_until_stop() is None:
            raise RuntimeError("the replay never armed")
        self.gdb.clear_break(armed)
        with open(FLAT_IMAGE, "rb") as f:
            self.flat = f.read()

    def close(self):
        try:
            self.gdb.close()
        finally:
            self.proc.kill()
            self.proc.wait()

    def reboot(self):
        """A fresh original: the drawing paths (the box and text routines) write
        through the game's screen pointers and can leave memory - code included -
        in a state no later case should inherit."""
        self.close()
        self.__init__(*self.args)

    # memory, by flat address
    def poke(self, address, data):
        write_block(self.gdb, linear(address), bytes(data))

    def peek(self, address, count):
        raw = read_block(self.gdb, linear(address), count)
        if raw is None:
            raise RuntimeError(f"read of {count} bytes at {address:#x} refused")
        return raw

    def poke32(self, address, value):
        self.poke(address, struct.pack("<I", value & 0xFFFFFFFF))

    def peek32(self, address):
        return struct.unpack("<I", self.peek(address, 4))[0]

    def restore_image(self, start, end):
        """Put the image's own bytes back over [start, end)."""
        self.poke(start, self.flat[start:end])

    # registers
    def set_reg(self, name, value):
        reply = self.gdb.cmd(f"P{REG_NUMBERS[name]:x}={struct.pack('<I', value & 0xFFFFFFFF).hex()}")
        if reply != "OK":
            raise RuntimeError(f"register write {name} refused: {reply!r}")

    def regs(self):
        reply = self.gdb.cmd("g")
        names = ["eax", "ecx", "edx", "ebx", "esp", "ebp", "esi", "edi", "eip"]
        return {name: int.from_bytes(bytes.fromhex(reply[i * 8:(i + 1) * 8]), "little")
                for i, name in enumerate(names)}

    def call(self, entry, stops, regs=None, limit_stops=1):
        """Run from `entry` until one of the flat addresses in `stops` is reached.

        `regs` are set first. Returns (flat address reached, registers there).
        The direction flag is cleared (the original's own `cld` is not on every
        path), and interrupts stay enabled.
        """
        for name, value in (regs or {}).items():
            self.set_reg(name, value)
        self.set_reg("eflags", 0x202)
        self.set_reg("eip", entry)
        for stop in stops:
            self.gdb.set_break(linear(stop))
        try:
            for _ in range(20):
                if self.gdb.cont_until_stop() is None:
                    raise RuntimeError(f"routine at {entry:#x} did not reach its end")
                regs_now = self.regs()
                if regs_now["eip"] in stops:
                    return regs_now["eip"], regs_now
        finally:
            for stop in stops:
                self.gdb.clear_break(linear(stop))
        raise RuntimeError("no stop of ours was reached")


def hexs(data):
    return bytes(data).hex()


# ----------------------------------------------------------------- the cases ---

ROSTER = 0x29582
ROSTER_BYTES = 1450
STRIDE = 43


def random_roster(rng, base):
    """A roster image with distinct per-pilot fields. `base` is the shipped file."""
    data = bytearray(base)
    counts = [rng.choice([0, 0, 1, 2, 2, 5, 9, 9, 120, 1000]) for _ in range(8)]
    for pilot in range(8):
        record = pilot * STRIDE
        for at in range(STRIDE - 1):
            data[record + at] = 0x30 + pilot * 3 + (at % 7)
        data[record + STRIDE - 1] = 0
        data[0x180 + pilot] = rng.randrange(4)
        for slot in range(10):
            data[0x188 + pilot * 10 + slot] = rng.randrange(10)
            data[0x55A + pilot * 10 + slot] = rng.randrange(2)
        struct.pack_into("<I", data, 0x1DA + pilot * 4, counts[pilot])
        struct.pack_into("<I", data, 0x1FA + pilot * 4, rng.randrange(1 << 20))
        struct.pack_into("<I", data, 0x21A + pilot * 4, rng.randrange(1 << 12))
        for slot in range(100):
            data[0x23A + pilot * 100 + slot] = rng.randrange(2)
    data[0x17F] = rng.randrange(8)
    return data


def case_roster_sort(original, count, seed):
    rng = random.Random(seed)
    base = open(os.path.join(ROOT, "assets", "extracted", "comanche_hdd", "COMANCHE.NAM"), "rb").read()
    cases = []
    inputs = [(bytearray(base), 0)]
    for _ in range(count):
        roster = random_roster(rng, base)
        inputs.append((roster, rng.randrange(8)))
    for roster, selected in inputs:
        original.poke(ROSTER, roster)
        original.poke(0x27DAA, bytes([selected]))
        stop, regs = original.call(0x29F36, [0x2A0FE])
        cases.append({
            "roster_in": hexs(roster), "selected_in": selected,
            "roster_out": hexs(original.peek(ROSTER, ROSTER_BYTES)),
            "selected_out": original.peek(0x27DAA, 1)[0],
        })
    return {"routine": "roster-sort", "entry": "00029F36", "end": "0002A0FE", "cases": cases}


