def case_format_number(original, count, seed):
    rng = random.Random(seed)
    values = [0, 1, 9, 10, 99, 100, 255, 256, 9999, 65535, 65536, 12345678, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF]
    cases = []
    for index in range(count):
        value = values[index] if index < len(values) else rng.choice([rng.randrange(1 << 32), rng.randrange(100000), rng.randrange(1000)])
        width = rng.randrange(1, 11)
        original.poke(SCRATCH, bytes([0xFC]) * 24)
        original.call(0x28C25, [0x28C3D], {"eax": value, "ecx": width, "edi": SCRATCH + 4})
        cases.append({"value": value, "width": width, "buffer_out": hexs(original.peek(SCRATCH, 24))})
    return {"routine": "format-number", "entry": "00028C25", "end": "00028C3D", "base": 4, "cases": cases}


def case_percent(original, count, seed):
    rng = random.Random(seed)
    cases = []
    for index in range(count):
        total = rng.choice([0, 1, 3, 7, 10, 30, 100, 255, 1000, rng.randrange(1 << 32), rng.randrange(100)])
        counted = rng.choice([0, 1, 5, total, total // 2 if total else 3, rng.randrange(1 << 32), rng.randrange(300)]) & 0xFFFFFFFF
        score = rng.choice([0, 1895, rng.randrange(1 << 32)])
        original.poke(SCRATCH, bytes([0xAA]) * 8)
        original.poke32(0x28258, score)
        original.poke32(0x2825C, 0)
        original.call(0x286F9, [0x2873C], {"edx": total, "ebx": counted, "edi": SCRATCH + 2})
        cases.append({"total": total, "count": counted, "score_in": score,
                      "buffer_out": hexs(original.peek(SCRATCH, 8)),
                      "score_out": original.peek32(0x28258), "last_out": original.peek32(0x2825C)})
    return {"routine": "percent", "entry": "000286F9", "end": "0002873C", "base": 2, "cases": cases}


def random_statistics_input(rng):
    scenario = rng.choice(["abort", "win", "lost", "nofuel", "partial", "wingman", "wingman-cheap", "random"])
    goals = rng.choice([0, 1, 3, 8, 26, rng.randrange(0, 31)])
    destroyed = goals if scenario in ("win", "wingman", "wingman-cheap") else (rng.randrange(0, goals + 1) if goals else 0)
    if scenario == "abort":
        destroyed = 0
    slots = list(range(1, 31))
    rng.shuffle(slots)
    table = {slot: {"active": 0, "aux": 0, "goal": 0} for slot in range(1, 31)}
    for index in range(goals):
        slot = slots[index]
        table[slot] = {"active": 0 if index < destroyed else 1, "aux": rng.choice([3, 6, 7, 8, 9]), "goal": 1}
    for slot in slots[goals:]:
        table[slot] = {"active": rng.randrange(2), "aux": rng.choice([0, 3, 6, 7, 8, 9, 4]), "goal": 0}
    hull_max = rng.choice([29, 30, 30, 5, 99, 0])
    hull_now = {"lost": -1, "random": rng.randrange(-3, 40)}.get(scenario, rng.randrange(0, hull_max + 1))
    if scenario in ("win", "abort", "partial", "nofuel", "wingman", "wingman-cheap"):
        hull_now = max(hull_now, 1) if hull_max else 0
    fuel_max = rng.choice([5000, 10000, 20000, 0, rng.randrange(1, 40000)])
    fuel = 0 if scenario == "nofuel" else rng.choice([fuel_max, fuel_max // 2, -5, rng.randrange(0, fuel_max + 1) if fuel_max else 0])
    ammo = [rng.randrange(0, 600) for _ in range(6)]
    loadout = [max(a, rng.randrange(0, 600)) for a in ammo]
    return {
        "table": table, "hull_now": hull_now, "hull_max": hull_max, "fuel": fuel, "fuel_max": fuel_max,
        "target_count": rng.choice([0, 8, 26, rng.randrange(0, 40)]),
        "ally": 1 if scenario in ("wingman", "wingman-cheap") else rng.choice([0, 0, 1]),
        "ammo": ammo, "loadout": loadout,
        "scenario": scenario,
    }


def case_statistics(original, count, seed):
    rng = random.Random(seed)
    cases = []
    for _ in range(count):
        c = random_statistics_input(rng)
        original.restore_image(*IMAGE_TEXT)
        for slot, o in c["table"].items():
            original.poke(0x21921 + slot, bytes([o["active"]]))
            original.poke(0x21DB3 + slot, bytes([o["aux"]]))
            original.poke(0x21F39 + slot, bytes([o["goal"]]))
        original.poke(0x28260, bytes([c["target_count"]]))
        original.poke32(0x19D60, c["fuel"])
        original.poke32(0x19D5C, c["fuel_max"])
        original.poke32(0x19E40, c["hull_now"])
        original.poke32(0x19E44, c["hull_max"])
        original.poke(0x19D2C, struct.pack("<6I", *c["ammo"]))
        original.poke(0x19D44, struct.pack("<6I", *c["loadout"]))
        original.poke(0x22384, bytes([c["ally"]]))
        original.call(0x28261, [0x284B0])
        cases.append({
            "input": {**{k: v for k, v in c.items() if k != "table"},
                      "objects": [[slot, o["active"], o["aux"], o["goal"]] for slot, o in sorted(c["table"].items())]},
            "text_out": hexs(original.peek(IMAGE_TEXT[0], IMAGE_TEXT[1] - IMAGE_TEXT[0])),
            "counters_out": hexs(original.peek(0x2824C, 0x14)),
            "fuel_out": struct.unpack("<i", original.peek(0x19D60, 4))[0],
            "hull_out": [struct.unpack("<i", original.peek(0x19E40, 4))[0], struct.unpack("<i", original.peek(0x19E44, 4))[0]],
        })
    return {"routine": "statistics", "entry": "00028261", "end": "000284B0", "cases": cases}


def random_text(rng, length):
    words = ["the", "enemy", "Comanche", "mission", "Hellfire", "|rYOU!|g", "wingman", "x", "a", "supercalifragilisticexpialidocious",
             "WWWWWWWWWWWWWWW", "iiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiiii", "night.", "it's", "Pick'em"]
    parts = []
    while sum(len(p) for p in parts) < length:
        parts.append(rng.choice(words))
        parts.append(rng.choice([" ", " ", " ", "  ", "\r\n", "\r\n", "\t", "^", " ^ ", "\n", "\r"]))
    return "".join(parts)


def case_briefing_loop(original, count, seed):
    rng = random.Random(seed)
    cases = []
    out = 0x2FB14 + 0x40
    for _ in range(count):
        length = rng.choice([40, 120, 400, 900])
        text = random_text(rng, length).encode("latin-1") + b"<" + bytes([rng.randrange(0x21, 0x7f)]) * 3
        prefix = bytes(rng.randrange(0x21, 0x7f) for _ in range(rng.randrange(0, 6)))
        original.poke(MISSION_BUFFER, prefix + text)
        original.poke(out, bytes([0xAA]) * 2048)
        stop, regs = original.call(0x290C0, [0x29119], {"esi": MISSION_BUFFER + len(prefix), "edi": out})
        end = regs["edi"]
        cases.append({"prefix": len(prefix), "text": hexs(text), "out": hexs(original.peek(out, end - out)),
                      "next": regs["esi"] - MISSION_BUFFER - len(prefix)})
    return {"routine": "briefing-loop", "entry": "000290C0", "end": "00029119", "cases": cases}


def mission_like_file(rng):
    count = rng.choice([0, 1, 3, 10, 12])
    lines = ["{Campaign %d}" % rng.randrange(10)]
    for k in range(count):
        name = rng.choice(["Oil Tank Holiday", "x", "A" * 27, "B" * 28, "C" * 31, "Werewolves on Patrol", "Wolfpack"])
        tail = rng.choice(["", "*", "*0", "*3", "*9", "*x", " *4"])
        lines.append("{%s}%s" % (name, tail))
        lines.append("Description line one of mission %d" % k)
        lines.append("<")
    text = "\r\n".join(lines) + "\r\n"
    if rng.random() < 0.15:
        text = text.replace("}", "", 1)
    return text.encode("latin-1")


def decoded_mission(name):
    raw = bytearray(open(os.path.join(ROOT, "assets", "extracted", "comanche_hdd", name), "rb").read())
    key = [3, 6, 0x12, 0x11]
    padded = raw + bytearray((-len(raw)) % 4)
    for i in range(len(padded)):
        padded[i] ^= key[i & 3]
    return bytes(padded[:len(raw)])


def case_scan_list(original, count, seed):
    rng = random.Random(seed)
    cases = []
    files = [decoded_mission("0.MIS"), decoded_mission("1.MIS")] + [mission_like_file(rng) for _ in range(count)]
    for data in files:
        original.poke(MISSION_BUFFER, data + bytes(8))
        original.poke32(0x15DC8, len(data))
        original.poke(0x29D95, bytes([0xCC]) * 0x160)
        original.poke(0x29F18, bytes([0xEE]) * 20)
        original.poke(0x29F2C, bytes([0xEE]) * 10)
        original.poke(0x29EF0, bytes([0xEE]) * 40)
        original.poke32(0x2A100, 0x1234)
        original.call(0x2A1E6, [0x2A299])
        cases.append({"file": hexs(data), "names": hexs(original.peek(0x29D95, 0x160)),
                      "star": hexs(original.peek(0x29F18, 10)), "promo": hexs(original.peek(0x29F2C, 10)),
                      "text": hexs(original.peek(0x29EF0, 40)), "count": original.peek32(0x2A100)})
    return {"routine": "scan-list", "entry": "0002A1E6", "end": "0002A299", "cases": cases}


def case_decode(original, count, seed):
    rng = random.Random(seed)
    cases = []
    for index in range(count):
        length = rng.choice([1, 3, 4, 5, 64, 257, 1000])
        data = bytes(rng.randrange(256) for _ in range(length))
        if index % 3 == 0:
            data = b"{" + data[1:]            # already plain: untouched
        padded = data + bytes((-len(data)) % 4)
        original.poke(MISSION_BUFFER, padded + bytes([0x55]) * 8)
        original.poke32(0x15DC8, len(data))
        original.call(0x2A2F8, [0x2A31C])
        cases.append({"data": hexs(data), "out": hexs(original.peek(MISSION_BUFFER, len(padded) + 8))})
    return {"routine": "decode", "entry": "0002A2F8", "end": "0002A31C", "cases": cases}


def case_skip_line(original, count, seed):
    rng = random.Random(seed)
    cases = []
    for _ in range(count):
        lines = []
        for _ in range(rng.randrange(1, 6)):
            lines.append(rng.choice(["", " ", "   indented", ";comment", "Text line", "\tTab", "x", "A" * rng.choice([5, 150, 170, 300])]))
        text = rng.choice(["\r\n", "\r", "\r\n"]).join(lines)
        if rng.random() < 0.8:
            text += "\r\nEnd"
        data = bytes(rng.randrange(0x41, 0x5a) for _ in range(rng.randrange(0, 20))) + text.encode("latin-1")
        start = rng.randrange(0, 8)
        original.poke(MISSION_BUFFER, data + bytes(0x200))
        stop, regs = original.call(0x2A29A, [0x2A2B7, 0x2A2B8], {"edi": MISSION_BUFFER + start})
        cases.append({"data": hexs(data), "start": start,
                      "error": stop == 0x2A2B8, "end": regs["edi"] - MISSION_BUFFER})
    return {"routine": "skip-line", "entry": "0002A29A", "end": "0002A2B7", "error": "0002A2B8", "cases": cases}


