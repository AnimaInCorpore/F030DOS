def case_pilot_record(original, count, seed):
    rng = random.Random(seed)
    base = open(NAM, "rb").read()
    cases = []
    for index in range(count):
        won = index % 2 == 1
        roster = random_roster(rng, base)
        pilot = rng.randrange(8)
        roster[0x17F] = pilot
        campaign = rng.randrange(2)
        roster[0x180 + pilot] = campaign
        digits = bytes([0x30, 0x31] + [0x32] * 8)
        mission = rng.randrange(10)
        star = bytes(rng.randrange(2) for _ in range(10))
        promo = bytes(rng.choice([0, 0, 1, 2, 5]) for _ in range(10))
        digit = digits[campaign] - 0x30
        roster[0x1D8] = mission
        for slot in range(10):
            roster[0x188 + pilot * 10 + slot] = roster[0x188 + pilot * 10 + slot] % 10
        roster[0x55A + pilot * 10 + digit] = 1 if rng.random() < 0.3 else 0
        for slot in range(32, 42):
            roster[pilot * STRIDE + slot] = rng.choice([0xFC, 0xFC, 0x31, 0x33])
        hull = 0 if (not won and rng.random() < 0.7) else rng.randrange(1, 30)
        score = rng.randrange(0, 20000)
        kills = rng.randrange(0, 40)
        original.poke(ROSTER, roster)
        original.poke(0x29D47, digits)
        original.poke(0x29F18, star)
        original.poke(0x29F2C, promo)
        original.restore_image(0x284B1, 0x286F9)
        original.poke32(0x19E40, hull)
        original.poke32(0x28258, score)
        original.poke32(0x28254, kills)
        if won:
            original.call(0x288ED, [0x289CF])
        else:
            original.call(0x287E2, [0x28898])
        cases.append({"won": won, "roster": hexs(roster), "digits": hexs(digits), "star": hexs(star), "promo": hexs(promo),
                      "hull": hull, "score": score, "kills": kills,
                      "roster_out": hexs(original.peek(ROSTER, ROSTER_BYTES)),
                      "message_out": hexs(original.peek(0x286A1, 0x2F))})
    return {"routine": "pilot-record", "entries": {"lost": "000287E2", "won": "000288ED"},
            "ends": {"lost": "00028898", "won": "000289CF"}, "cases": cases}


