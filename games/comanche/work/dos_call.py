#!/usr/bin/env python3
r"""Call routines of the original directly, with chosen inputs, and read what they leave.

The running original is stopped as a replay arms (so the game's state, stack and
interrupts are alive), and each case then writes its inputs into memory and
registers through the gdbstub, points EIP at a routine's entry, and runs to a
breakpoint on the instruction that ends it - before that instruction executes, so
the stack never needs a valid return address. The routine's outputs are read back
from memory and registers. This is the oracle for pure routines whose inputs a
port can choose freely: the number formatter, the statistics, the ranking sort,
the briefing wrap, the pilot-record paths, the options toggles, the name entry.

    python3 work/dos_call.py roster-sort --out work/replay_dos/dos-call-roster-sort.json

Cases are generated from a fixed seed, so a capture can be regenerated byte for
byte. The game runs on a snapshot of the disk image; nothing is written back.

N/A - target artefact: an oracle probe, no DOS routine.
"""
import argparse
import json
import os
import random
import struct
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from inspect_qemu_state import Qmp, default_hdd, QEMU, ROOT
