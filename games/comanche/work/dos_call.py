GAME_KEY_LOOPS = (0x26DF8, 0x26E81)


def case_game_column(original, count, seed):
    cases = []
    final = (0x2873D, 0x6B14, 0x2615C, 0x26E06, 0x26E8F)
    for code in (0, 1, 2, 3, 4, 5, 0x20, 0x7F, 0x80, 0x10):
        original.reboot()
        original.poke(0x25DBC, bytes(range(0x40, 0x40 + 35)))
        writes = []
        stops = list(final) + list(GAME_KEY_LOOPS) + [0x15D40]
        for address in stops:
            original.gdb.set_break(linear(address))
        original.set_reg("eax", code)
        original.set_reg("eflags", 0x202)
        original.set_reg("eip", 0x26D8B)
        end = None
        try:
            for _ in range(40):
                if original.gdb.cont_until_stop() is None:
                    raise RuntimeError("game column stalled")
                regs = original.regs()
                at = regs["eip"]
                if at in final:
                    end = at
                    break
                if at == 0x15D40:
                    writes.append({"edx": regs["edx"], "ebx": regs["ebx"]})
                if at in GAME_KEY_LOOPS:
                    original.poke32(0x1B70, 0x1C)
                original.gdb.clear_break(linear(at))
                original.gdb.step()
                original.gdb.set_break(linear(at))
        finally:
            for address in stops:
                original.gdb.clear_break(linear(address))
        cases.append({"code": code, "end": f"{end:08X}" if end is not None else None, "writes": writes})
    return {"routine": "game-column", "entry": "00026D8B", "cases": cases}


SWITCH_CODES = [0x2E, 0x2D, 0x14, 0x15, 0x30, 0x31, 0x32]
BRACES = {0x2E: 0x2677A, 0x2D: 0x26767, 0x14: 0x266A0, 0x15: 0x266A9, 0x30: 0x267AC, 0x31: 0x267C1, 0x32: 0x267D2}


def case_toggles(original, count, seed):
    rng = random.Random(seed)
    cases = []
    for index in range(count):
        code = SWITCH_CODES[index % 7] if index < 14 else rng.choice(SWITCH_CODES)
        settings = bytes(rng.randrange(256) for _ in range(35))
        braces = {addr: rng.choice([0x7B, 0x7D]) for addr in BRACES.values()}
        original.poke(0x25DBC, settings)
        for addr, value in braces.items():
            original.poke(addr, bytes([value]))
        original.call(0x26AB6, [0x26E8F], {"eax": code})
        cases.append({"code": code, "settings": hexs(settings), "braces": {f"{a:X}": v for a, v in braces.items()},
                      "settings_out": hexs(original.peek(0x25DBC, 35)),
                      "braces_out": {f"{a:X}": original.peek(a, 1)[0] for a in BRACES.values()}})
    return {"routine": "toggles", "entry": "00026AB6", "end": "00026E8F", "cases": cases}


NAME_LOOP = 0x2807E
NAME_END = 0x28215


def case_name_entry(original, count, seed):
    rng = random.Random(seed)
    base = open(NAM, "rb").read()
    lower = original.flat[0x19E9:0x19E9 + 128]
    letters = [i for i in range(128) if lower[i] and chr(lower[i]).isalpha()]
    wide = [i for i in range(128) if lower[i] in b"wmWM"]
    cases = []
    for index in range(count):
        kind = index % 6
        if kind == 0:
            keys = [(rng.choice(letters), rng.random() < 0.3) for _ in range(rng.randrange(1, 12))]
        elif kind == 1:
            keys = [(rng.choice(wide), True) for _ in range(30)]
        elif kind == 2:
            keys = [(letters[0], False)] * 40
        elif kind == 3:
            keys = [(rng.choice(letters + [0x39, 0x0E, 0x0E, 0x02, 0x0C]), rng.random() < 0.4) for _ in range(rng.randrange(3, 25))]
        elif kind == 4:
            keys = [(0x0E, False)]
        else:
            keys = [(rng.choice(letters), False) for _ in range(rng.randrange(1, 6))]
        ending = rng.choice([0x1C, 0x1C, 0x1C, 0x01]) if kind != 4 else 0x1C
        keys = keys + [(ending, False)]
        roster = random_roster(rng, base)
        slot = rng.randrange(8)
        original.poke(ROSTER, roster)
        original.poke(0x27DAA, bytes([slot]))
        original.poke32(0x1B70, 0)
        original.set_reg("eflags", 0x202)
        pending = list(keys)
        stops = [NAME_LOOP, NAME_END]
        for address in stops:
            original.gdb.set_break(linear(address))
        original.set_reg("eip", 0x2800C)
        try:
            for _ in range(len(keys) + 40):
                if original.gdb.cont_until_stop() is None:
                    raise RuntimeError("name entry stalled")
                regs = original.regs()
                if regs["eip"] == NAME_END:
                    break
                if regs["eip"] != NAME_LOOP:
                    continue
                if pending:
                    code, shift = pending.pop(0)
                    original.poke32(0x1B70, code)
                    original.poke(0x1A9A, bytes([0x00 if shift else 0xFF]))
                    original.poke(0x1AA6, bytes([0xFF]))
                else:
                    original.poke32(0x1B70, 0)
                original.gdb.clear_break(linear(NAME_LOOP))
                original.gdb.step()
                original.gdb.set_break(linear(NAME_LOOP))
        finally:
            for address in stops:
                original.gdb.clear_break(linear(address))
        cases.append({"keys": [[c, s] for c, s in keys], "roster": hexs(roster), "slot": slot,
                      "roster_out": hexs(original.peek(ROSTER, ROSTER_BYTES)),
                      "field_out": hexs(original.peek(0x27FEA, 32)), "cursor_out": original.peek(0x2800B, 1)[0],
                      "selected_out": original.peek(0x27DAA, 1)[0]})
    return {"routine": "name-entry", "entry": "0002800C", "end": "00028215", "cases": cases}


