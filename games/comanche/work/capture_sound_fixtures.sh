#!/bin/sh
# Capture every sound fixture the proof tool compares the JavaScript driver with:
# the scenarios of work/trace_sound_writes.py (direct mode, about half an hour in all)
# and, with NATURAL=<seconds>, one natural run of the game.
#
#   sh work/capture_sound_fixtures.sh                # build/sound/*.json
#   NATURAL=400 sh work/capture_sound_fixtures.sh    # and build/sound-natural/natural-attract.json
#   node tools/check-js-sound.js                     # compare (also run by tools/prove-browser-attract.js)
#
# Runs one QEMU at a time on QMP 4717 / gdb 4718 (QMP_PORT, GDB_PORT override).
# Do not edit this file while it runs: sh reads it as it goes.
# N/A - target artefact: an oracle probe driver, no DOS routine.
set -e
cd "$(dirname "$0")/.."
OUT=build/sound
mkdir -p "$OUT"
# the AdLib, the PC speaker, the empty device and the digital layer
for s in select-adlib select-sb select-bad openmus menumus1 menumus2 fanfare musday musnight musvolc \
         muswin muslose winmus bigwin openmus-volume effects effects-volume effect-over-music \
         queue-and-loop wrap-inc-bx openmus-speaker fanfare-speaker openmus-none \
         synthetic-events synthetic-links effects-speaker \
         digital-explosion digital-launch digital-cannon digital-rotor digital-speech digital-mix; do
  python3 work/trace_sound_writes.py direct --scenario "$s" --out "$OUT/$s.json" </dev/null
done
# no card in the guest at all
python3 work/trace_sound_writes.py direct --scenario detect-absent --no-adlib --mpu --out "$OUT/detect-absent.json" </dev/null
# the MPU-401 (QEMU has none: its two port routines are skipped and acknowledged)
for s in openmus-mpu fanfare-mpu musday-mpu device-switch effects-mpu; do
  python3 work/trace_sound_writes.py direct --scenario "$s" --mpu --out "$OUT/$s.json" </dev/null
done
# one run of the game, with its timer interrupts
if [ -n "$NATURAL" ]; then
  python3 work/trace_sound_writes.py natural --seconds "$NATURAL" --out build/sound-natural/natural-attract.json </dev/null
fi
