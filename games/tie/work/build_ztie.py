#!/usr/bin/env python3
"""P4.2 build order: reassemble Z_TIE__.EXE from its parts and verify.

  python3 work/build_ztie.py [--out work/build/Z_TIE__.EXE]

Every region is REBUILT (emitted from a disassembly and proven by the reassembly
ratchet, analysis/reassembly.md), GENERATED (re-encoded from decoded structures
-- work/build_fixups.py) or COPIED (still taken verbatim because nothing
regenerates it yet). The report prints which is
which, so "byte-identical" is never mistaken for "fully reconstructed" -- a
build made entirely of copied regions would pass trivially and mean nothing.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_fixups                 # noqa: E402

EXE = "game/SWTieCD/TIECD/Z_TIE__.EXE"
STUB_BIN = "work/ratchet/stub.bin"       # 16-bit load module, ratchet16.py
OBJ1_BIN = "work/ratchet32/stub.bin"     # 32-bit obj1,        ratchet16.py --unit obj1
OBJ2_BIN = "work/obj2/obj2.bin"          # obj2 data,          type_obj2.py --emit


def regions(orig):
    hdr = struct.unpack_from("<H", orig, 8)[0] * 16
    image = (struct.unpack_from("<H", orig, 4)[0] - 1) * 512 + \
        struct.unpack_from("<H", orig, 2)[0]
    lfanew = struct.unpack_from("<I", orig, 0x3C)[0]
    le = lfanew
    dpo = struct.unpack_from("<I", orig, le + 0x80)[0]
    otab = le + struct.unpack_from("<I", orig, le + 0x40)[0]
    nobj = struct.unpack_from("<I", orig, le + 0x44)[0]
    objs = [struct.unpack_from("<IIIIII", orig, otab + 24 * i) for i in range(nobj)]
    psize = struct.unpack_from("<I", orig, le + 0x28)[0]
    obj1_bytes = objs[0][4] * psize
    _fpt, _frt, (fpt_lo, fpt_hi), (frt_lo, frt_hi) = build_fixups.rebuild()
    return [
        ("MZ header",            0,            hdr,                     "COPIED",  None),
        ("16-bit stub",          hdr,          image,                   "REBUILT", STUB_BIN),
        ("pad to LE header",     image,        lfanew,                  "COPIED",  None),
        ("LE hdr + obj table",   lfanew,       fpt_lo,                  "COPIED",  None),
        ("fixup page table",     fpt_lo,       fpt_hi,                  "GENERATED", "build_fixups.rebuild()"),
        ("fixup records",        frt_lo,       frt_hi,                  "GENERATED", "build_fixups.rebuild()"),
        ("import table + pad",   frt_hi,       dpo,                     "COPIED",  None),
        ("obj1 pages (code)",    dpo,          dpo + obj1_bytes,        "REBUILT", OBJ1_BIN),
        ("obj2 pages (data)",    dpo + obj1_bytes, len(orig),           "REBUILT", OBJ2_BIN),
    ]


def main():
    out = sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv \
        else "work/build/Z_TIE__.EXE"
    orig = open(EXE, "rb").read()
    fpt, frt, _a, _b = build_fixups.rebuild()
    GEN = {"fixup page table": fpt, "fixup records": frt}
    parts, rebuilt, copied, bad = [], 0, 0, []
    print(f"{'region':<22} {'file range':<21} {'bytes':>9}  source")
    for name, lo, hi, kind, src in regions(orig):
        want = orig[lo:hi]
        if kind == "GENERATED":
            got = GEN[name]
            if got != want:
                bad.append(f"{name}: generated bytes differ from the original")
                got = want
            rebuilt += len(want)
        elif kind == "REBUILT":
            if not os.path.exists(src):
                print(f"  MISSING {src} -- run the ratchet first")
                return 1
            got = open(src, "rb").read()
            if len(got) != len(want):
                bad.append(f"{name}: {src} is {len(got)} B, region is {len(want)} B")
                got = want
            elif got != want:
                bad.append(f"{name}: {src} differs from the original")
            rebuilt += len(want)
        else:
            got = want
            copied += len(want)
        parts.append(got)
        print(f"  {name:<20} {lo:#08x}..{hi:#08x} {hi - lo:>9}  {kind}"
              + (f"  <- {src}" if src else ""))

    built = b"".join(parts)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "wb").write(built)
    total = len(orig)
    print(f"\nwrote {out} ({len(built)} B)")
    print(f"byte-identical to the original: {built == orig}")
    print(f"  rebuilt / generated:      {rebuilt:>7} B ({100*rebuilt/total:.1f}%)")
    print(f"  copied verbatim:          {copied:>7} B ({100*copied/total:.1f}%)")
    print("\n  \"rebuilt/generated\" means the bytes come from source we emit, NOT that")
    print("  they are understood. Quality of what is emitted, measured separately:")
    print("    16-bit stub   83.5 % real instructions (net of the data guard)")
    print("    obj1          93.2 % real instructions (net of the data guard)")
    print("    fixup tables  100 %  -- all 27,438 records round-trip")
    print("    obj2          58.8 % typed (pointer/string/zero); 41.2 % is raw db")
    for b in bad:
        print(f"  PROBLEM: {b}")
    return 1 if (built != orig or bad) else 0


if __name__ == "__main__":
    sys.exit(main())
