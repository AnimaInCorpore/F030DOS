#!/usr/bin/env python3
"""Re-emit records in UW2's standard `.GR` archive container."""
import struct

from gr8_encode import encode_type8_record


def _pack4(nibbles, trailing=0):
    out = bytearray()
    for i in range(0, len(nibbles), 2):
        hi = nibbles[i]
        lo = nibbles[i + 1] if i + 1 < len(nibbles) else trailing
        out.append((hi << 4) | lo)
    return bytes(out)


def _encode_type10(record):
    width, height = record[1], record[2]
    count = width * height
    payload = record[5:]
    packed_len = (count + 1) // 2
    if len(payload) < packed_len:
        raise ValueError("type-0a payload is shorter than width*height")
    nibbles = []
    for b in payload[:packed_len]:
        nibbles.extend((b >> 4, b & 0xF))
    trailing = payload[packed_len - 1] & 0xF if count & 1 else 0
    # The byte after the packed pixels is unreferenced format slack; carry it.
    return record[:5] + _pack4(nibbles[:count], trailing) + payload[packed_len:]


def encode_record(record, allpals):
    """Re-emit one standard-format record from its decoded representation."""
    if not record:
        return record
    rtype = record[0]
    if rtype == 8:
        return encode_type8_record(record, allpals)
    if rtype == 4:
        width, height = record[1], record[2]
        if len(record) != 5 + width * height:
            raise ValueError("type-4 payload length does not equal width*height")
        return record[:5] + record[5:]
    if rtype == 10:
        return _encode_type10(record)
    raise ValueError(f"unsupported standard .GR record type: {rtype:#x}")


def rebuild_archive(data, allpals):
    """Rebuild the standard container and return its regenerated bytes."""
    if len(data) < 7:
        raise ValueError(".GR file is too short")
    count = struct.unpack_from("<H", data, 1)[0]
    offsets = [data[3 + 4 * i] |
               (data[4 + 4 * i] << 8) |
               (data[5 + 4 * i] << 16)
               for i in range(count + 1)]
    table_end = 3 + 4 * (count + 1)
    if offsets[0] != table_end:
        raise ValueError("non-standard .GR table start")

    out = bytearray(data[:3])
    table_at = len(out)
    out += b"\0" * (4 * (count + 1))
    new_offsets = []
    for i in range(count):
        start, end = offsets[i], offsets[i + 1]
        if end < start or end > len(data):
            raise ValueError(f"bad .GR record bounds at index {i}")
        new_offsets.append(len(out))
        out += encode_record(data[start:end], allpals)
    new_offsets.append(len(out))
    for i, off in enumerate(new_offsets):
        out[table_at + 4 * i:table_at + 4 * i + 3] = bytes((
            off & 0xFF, (off >> 8) & 0xFF, (off >> 16) & 0xFF))
    return bytes(out)
